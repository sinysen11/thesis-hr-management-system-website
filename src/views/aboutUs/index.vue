<script>
import { getAllMainContent } from '@/services/product-solution';

export default {
  name: 'About',
  data() {
    return {
      isMobileMenuOpen: false,
      isProductsMenuOpen: false,
      mainContents: [],
      isLoading: false,
      error: null
    };
  },
  methods: {
    async fetchMainContents() {
      this.isLoading = true;
      this.error = null;
      try {
        const response = await getAllMainContent();
        if (response && response.status === 1 && response.data) {
          this.mainContents = response.data
            .filter(item => item.status === 'ACTIVE')
            .map(item => ({
              id: item._id,
              type: item.type,
              title: item.title,
              slug: item.title.toLowerCase().replace(/\s+/g, '-'), // Generate slug from title
              description: item.description,
              images: item.images
            }));
        } else {
          this.error = 'No active products found';
        }
      } catch (error) {
        this.error = 'Failed to fetch products';
        console.error('Error fetching main contents:', error);
      } finally {
        this.isLoading = false;
      }
    },
    toggleMobileMenu() {
      this.isMobileMenuOpen = !this.isMobileMenuOpen;
    },
    toggleProductsMenu() {
      this.isProductsMenuOpen = !this.isProductsMenuOpen;
    },
    scrollToTop() {
      window.scrollTo({ top: 0, behavior: 'smooth' });
    }
  },
  mounted() {
    this.fetchMainContents();
  }
};
</script>

